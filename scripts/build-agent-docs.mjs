// Builds the AI-agent documentation index from each component's USAGE.md.
//
// Writes:
//   llms.txt                                      index for agents building SwiftUI apps with
//                                                 Sparkline, linking docs/agents/ and every USAGE.md
//   Sources/Sparkline/Sparkline.docc/Components/  one DocC article per component, from its USAGE.md
//
// Usage: node scripts/build-agent-docs.mjs

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const componentsDir = join(root, 'Sources/Sparkline/Components');
const agentsDir = join(root, 'docs/agents');

// First paragraph after the H1 is the one-line summary used in the index.
function summary(markdown) {
  const lines = markdown.split('\n');
  const start = lines.findIndex((l) => l.startsWith('# ')) + 1;
  const para = [];
  for (const line of lines.slice(start)) {
    if (!line.trim()) {
      if (para.length) break;
      continue;
    }
    para.push(line.trim());
  }
  return para.join(' ');
}

function title(markdown) {
  return markdown.match(/^# (.+)$/m)?.[1] ?? '';
}

const components = readdirSync(componentsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(componentsDir, d.name, 'USAGE.md')))
  .map((d) => {
    const md = readFileSync(join(componentsDir, d.name, 'USAGE.md'), 'utf8');
    return { folder: d.name, name: title(md), summary: summary(md) };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const guides = [
  { file: 'building-with-sparkline.md', label: 'Building an app with Sparkline', note: 'setup, rules, and what to do when a component is missing. Read first.' },
  { file: 'tokens.md', label: 'Tokens', note: 'semantic color, spacing, radius, shadow and type tokens for app code.' },
];
for (const g of guides) {
  if (!existsSync(join(agentsDir, g.file))) throw new Error(`Missing guide docs/agents/${g.file}`);
}

const llms = `# Sparkline Design System for SwiftUI

> SwiftUI component library for iOS and iPadOS, distributed as a Swift package. Every component is themed through semantic color tokens that follow the system light/dark setting. These docs are written for AI coding agents building product screens from the library.

Before writing UI: add the \`Sparkline\` package, call \`SPFonts.register()\` once at launch, and use the Sparkline component for any control that has one. Bind values with \`Binding\`s, handle actions with closures, and disable with \`.disabled(_:)\`. Style app code with \`Color.sp…\`, \`SPSpacing\`, \`SPRadius\`, \`.spShadow\` and \`.spTextStyle\` only.

## Guides

${guides.map((g) => `- [${g.label}](docs/agents/${g.file}): ${g.note}`).join('\n')}

## Components

${components.map((c) => `- [${c.name}](Sources/Sparkline/Components/${c.folder}/USAGE.md): ${c.summary}`).join('\n')}
`;

writeFileSync(join(root, 'llms.txt'), llms);

// DocC component articles are generated from the same USAGE.md files, so the
// agent docs and the Xcode documentation never drift apart.
const symbols = {
  Avatar: ['SPAvatar'],
  Badge: ['SPBadge'],
  Button: ['SPButton', 'SPButtonStyle'],
  ButtonGroup: ['SPButtonGroup', 'SPButtonGroupSize'],
  Card: ['SPCard', 'SPCardVariant', 'SPCardPadding'],
  Checkbox: ['SPCheckbox'],
  Chip: ['SPChip'],
  Icon: ['SPIcon', 'SPIconShape', 'SPIconName'],
  Input: ['SPInput'],
  Radio: ['SPRadioGroup', 'SPRadio'],
  Select: ['SPSelect', 'SPSelectOption', 'SPSelectState'],
  Slider: ['SPSlider'],
  Stepper: ['SPStepper'],
  Switch: ['SPSwitch', 'SPSwitchToggleStyle'],
};
const articlesDir = join(root, 'Sources/Sparkline/Sparkline.docc/Components');
mkdirSync(articlesDir, { recursive: true });
for (const c of components) {
  const md = readFileSync(join(componentsDir, c.folder, 'USAGE.md'), 'utf8');
  const body = md
    .replace(/^# .+\n+/, '')
    .replace(/^.+\n+/, '') // the summary paragraph becomes the abstract
    .replace(/```swift\nimport Sparkline\n```\n+/, '')
    .trim();
  const syms = symbols[c.folder];
  if (!syms) throw new Error(`No DocC symbols listed for ${c.folder}`);
  const article = `# ${c.name}

${c.summary}

${body}

## Topics

### API

${syms.map((s) => `- \`\`${s}\`\``).join('\n')}

<!-- GENERATED by scripts/build-agent-docs.mjs from Components/${c.folder}/USAGE.md. Edit the USAGE.md instead. -->
`;
  writeFileSync(join(articlesDir, `${c.folder}Article.md`), article);
}

console.log(`Agent docs: ${components.length} components, ${guides.length} guides -> llms.txt, ${components.length} DocC articles`);
