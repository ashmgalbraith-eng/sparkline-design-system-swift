// Generates Sparkline's color tokens from the Angular design system's CSS.
//
// Source of truth: ../sparkline-design-system/src/styles/global.css
//   :root                 primitive palette (--primary-50, --neutral-20, ...)
//   [data-theme="light"]  semantic tokens for light mode
//   [data-theme="dark"]   semantic tokens for dark mode
//
// Writes Sources/Sparkline/Tokens/SPColor+Generated.swift:
//   SPPrimitive           internal primitive palette
//   Color.sp<Name>        one public dynamic color per semantic token (light + dark)
//   Color.spFocusRing     --primary-30, the one primitive components may use
//
// Usage: node scripts/generate-tokens.mjs [path/to/global.css]

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cssPath = process.argv[2] ?? join(root, '../sparkline-design-system/src/styles/global.css');
const outPath = join(root, 'Sources/Sparkline/Tokens/SPColor+Generated.swift');

const css = readFileSync(cssPath, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

function block(selector) {
  const start = css.indexOf(selector);
  if (start < 0) throw new Error(`Selector ${selector} not found in ${cssPath}`);
  const open = css.indexOf('{', start);
  const close = css.indexOf('}', open);
  return css.slice(open + 1, close);
}

function declarations(body) {
  const out = new Map();
  for (const m of body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) out.set(m[1], m[2].trim());
  return out;
}

const primitives = new Map(
  [...declarations(block(':root'))].filter(([, v]) => /^#[0-9a-f]{6}$/i.test(v)),
);
const light = declarations(block('[data-theme="light"]'));
const dark = declarations(block('[data-theme="dark"]'));

function resolve(value, token, theme) {
  const ref = value.match(/^var\(--([\w-]+)\)$/);
  if (ref) {
    const hex = primitives.get(ref[1]);
    if (!hex) throw new Error(`${theme} ${token}: unknown primitive ${ref[1]}`);
    return { hex, primitive: ref[1] };
  }
  if (/^#[0-9a-f]{6}$/i.test(value)) return { hex: value, primitive: null };
  throw new Error(`${theme} ${token}: unsupported value ${value}`);
}

const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^\w/, (c) => c.toUpperCase());
const hex = (h) => `0x${h.slice(1).toUpperCase()}`;

const semantic = [...light.keys()].filter((k) => k.startsWith('color-'));
for (const k of semantic) if (!dark.has(k)) throw new Error(`${k} has no dark value`);

const lines = [];
lines.push('// GENERATED by scripts/generate-tokens.mjs from sparkline-design-system/src/styles/global.css.');
lines.push('// Do not edit by hand. Re-run `node scripts/generate-tokens.mjs` after changing the CSS tokens.');
lines.push('');
lines.push('import SwiftUI');
lines.push('');
lines.push('/// The primitive palette. Internal: components and apps use the semantic `Color.sp…` tokens.');
lines.push('enum SPPrimitive {');
for (const [name, value] of primitives) lines.push(`    static let ${camel(name)} = Color(hex: ${hex(value)})`);
lines.push('}');
lines.push('');
lines.push('public extension Color {');
lines.push('    /// Focus ring color (`--primary-30`). The only primitive components may use directly.');
lines.push('    static let spFocusRing = SPPrimitive.primary30');
lines.push('');
for (const token of semantic) {
  const name = token.replace(/^color-/, '');
  const l = resolve(light.get(token), token, 'light');
  const d = resolve(dark.get(token), token, 'dark');
  const doc = `--${token}: light ${l.primitive ?? l.hex}, dark ${d.primitive ?? d.hex}`;
  lines.push(`    /// \`${doc}\``);
  lines.push(`    static let sp${pascal(name)} = Color(light: ${hex(l.hex)}, dark: ${hex(d.hex)})`);
}
lines.push('}');
lines.push('');
lines.push('public extension ShapeStyle where Self == Color {');
lines.push('    static var spFocusRing: Color { .spFocusRing }');
for (const token of semantic) {
  const n = `sp${pascal(token.replace(/^color-/, ''))}`;
  lines.push(`    static var ${n}: Color { Color.${n} }`);
}
lines.push('}');
lines.push('');
lines.push('/// Every semantic color token, for galleries and tests.');
lines.push('public enum SPColorToken: String, CaseIterable, Sendable {');
for (const token of semantic) lines.push(`    case ${camel(token.replace(/^color-/, ''))} = "${token}"`);
lines.push('');
lines.push('    public var color: Color {');
lines.push('        switch self {');
for (const token of semantic) {
  const c = camel(token.replace(/^color-/, ''));
  lines.push(`        case .${c}: return .sp${pascal(token.replace(/^color-/, ''))}`);
}
lines.push('        }');
lines.push('    }');
lines.push('}');
lines.push('');

writeFileSync(outPath, lines.join('\n'));
console.log(`Tokens: ${primitives.size} primitives, ${semantic.length} semantic colors -> ${outPath.replace(root + '/', '')}`);
