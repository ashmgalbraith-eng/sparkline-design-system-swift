// Generates every Sparkline design token from the Angular design system's CSS,
// so web and iOS share one set of token names and values.
//
// Source of truth: ../sparkline-design-system/src/styles/global.css
//   :root                          primitives, spacing, radius, shadows, type (compact)
//   @media (min-width: 768px)      type overrides, used at regular width (iPad)
//   [data-theme="light"|"dark"]    semantic colors
//
// Naming rule: --{group}-{name} becomes SP{Group}.{camelName}
//   --color-surface-brand   SPColor.surfaceBrand
//   --spacing-md            SPSpacing.md
//   --radius-lg             SPRadius.lg
//   --shadow-md             SPShadow.md
//   --type-headline-1-*     SPType.headline1
//
// Writes Sources/Sparkline/Tokens/SPTokens+Generated.swift.
// Usage: node scripts/generate-tokens.mjs [path/to/global.css]

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cssPath = process.argv[2] ?? join(root, '../sparkline-design-system/src/styles/global.css');
const outPath = join(root, 'Sources/Sparkline/Tokens/SPTokens+Generated.swift');

const css = readFileSync(cssPath, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

/** The body of the first `{ … }` rule for `selector`, searching from `from`. */
function block(selector, from = 0) {
  const start = css.indexOf(selector, from);
  if (start < 0) throw new Error(`Selector ${selector} not found in ${cssPath}`);
  const open = css.indexOf('{', start);
  const close = css.indexOf('}', open);
  return css.slice(open + 1, close);
}

function declarations(body) {
  const out = new Map();
  for (const m of body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) out.set(m[1], m[2].trim());
  return out;
}

/** Tokens in group `prefix`, keyed by the rest of the name. */
function group(decls, prefix) {
  return new Map([...decls].filter(([k]) => k.startsWith(prefix)).map(([k, v]) => [k.slice(prefix.length), v]));
}

const media = css.indexOf('@media (min-width: 768px)');
if (media < 0) throw new Error('@media (min-width: 768px) not found');
const rootDecls = declarations(block(':root'));
const regularDecls = declarations(block(':root', media));
const light = declarations(block('[data-theme="light"]'));
const dark = declarations(block('[data-theme="dark"]'));

const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const hex = (h) => `0x${h.slice(1).toUpperCase()}`;
const px = (v, token) => {
  const m = v.match(/^(-?[\d.]+)(px)?$/);
  if (!m) throw new Error(`--${token}: expected px, got ${v}`);
  return Number(m[1]);
};
const num = (n) => String(Number(n.toFixed(2)));

const lines = [];
const out = (s = '') => lines.push(s);

out('// GENERATED by scripts/generate-tokens.mjs from sparkline-design-system/src/styles/global.css.');
out('// Do not edit by hand. Re-run `node scripts/generate-tokens.mjs` after changing the CSS tokens.');
out();
out('import SwiftUI');

// ── Colors ──────────────────────────────────────────────────────────────────

const primitives = new Map([...rootDecls].filter(([, v]) => /^#[0-9a-f]{6}$/i.test(v)));

function resolve(value, token, theme) {
  const ref = value.match(/^var\(--([\w-]+)\)$/);
  if (ref) {
    const h = primitives.get(ref[1]);
    if (!h) throw new Error(`${theme} --color-${token}: unknown primitive ${ref[1]}`);
    return { hex: h, source: ref[1] };
  }
  if (/^#[0-9a-f]{6}$/i.test(value)) return { hex: value, source: value };
  throw new Error(`${theme} --color-${token}: unsupported value ${value}`);
}

const colors = [...group(light, 'color-').keys()];
for (const name of colors) if (!dark.has(`color-${name}`)) throw new Error(`--color-${name} has no dark value`);

out();
out('/// The primitive palette. Internal: components and apps use `SPColor`.');
out('enum SPPrimitive {');
for (const [name, value] of primitives) out(`    static let ${camel(name)} = Color(hex: ${hex(value)})`);
out('}');
out();
out('/// Semantic colors (`--color-*`). Each resolves to its light or dark value from the color scheme.');
out('public enum SPColor {');
out('    /// `--primary-30`: the focus ring, the one primitive components may use directly.');
out('    public static let focusRing = SPPrimitive.primary30');
for (const name of colors) {
  const l = resolve(light.get(`color-${name}`), name, 'light');
  const d = resolve(dark.get(`color-${name}`), name, 'dark');
  out();
  out(`    /// \`--color-${name}\`: light ${l.source}, dark ${d.source}`);
  out(`    public static let ${camel(name)} = Color(light: ${hex(l.hex)}, dark: ${hex(d.hex)})`);
}
out('}');
out();
out('/// Every semantic color with its CSS name, for galleries and tests.');
out('public enum SPColorToken: String, CaseIterable, Sendable {');
for (const name of colors) out(`    case ${camel(name)} = "--color-${name}"`);
out();
out('    public var color: Color {');
out('        switch self {');
for (const name of colors) out(`        case .${camel(name)}: return SPColor.${camel(name)}`);
out('        }');
out('    }');
out('}');

// ── Spacing and radius ──────────────────────────────────────────────────────

for (const [prefix, type, doc] of [
  ['spacing-', 'SPSpacing', 'Spacing scale (`--spacing-*`), in points.'],
  ['radius-', 'SPRadius', 'Corner radius scale (`--radius-*`), in points.'],
]) {
  const tokens = group(rootDecls, prefix);
  if (!tokens.size) throw new Error(`No --${prefix}* tokens found`);
  out();
  out(`/// ${doc}`);
  out(`public enum ${type} {`);
  for (const [name, value] of tokens) {
    out(`    /// \`--${prefix}${name}: ${value}\``);
    out(`    public static let ${camel(name)}: CGFloat = ${num(px(value, prefix + name))}`);
  }
  out('}');
}

// ── Shadows ─────────────────────────────────────────────────────────────────
// CSS blur is about twice SwiftUI's shadow radius. SwiftUI has no spread, so a
// negative spread is folded into a smaller radius: radius = (blur + spread) / 2.

const shadowPattern = /^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$/;
const shadows = [...group(rootDecls, 'shadow-')].map(([name, value]) => {
  const m = value.match(shadowPattern);
  if (!m) throw new Error(`--shadow-${name}: unsupported value ${value}`);
  const [x, y, blur, spread, r, g, b, a] = m.slice(1).map(Number);
  const rgb = `0x${[r, g, b].map((c) => c.toString(16).padStart(2, '0')).join('').toUpperCase()}`;
  return { css: name, name: camel(name), value, x, y, radius: Math.max(0, (blur + spread) / 2), rgb, a };
});

out();
out('/// Elevation shadows (`--shadow-*`). Apply with `.spShadow(_:)`.');
out('public enum SPShadow: String, CaseIterable, Sendable {');
for (const s of shadows) {
  out(`    /// \`--shadow-${s.css}: ${s.value}\``);
  out(`    case ${s.name} = "--shadow-${s.css}"`);
}
out();
out('    var color: Color {');
out('        switch self {');
for (const s of shadows) out(`        case .${s.name}: return Color(hex: ${s.rgb}, opacity: ${num(s.a)})`);
out('        }');
out('    }');
for (const field of ['radius', 'x', 'y']) {
  out();
  out(`    var ${field}: CGFloat {`);
  out('        switch self {');
  for (const s of shadows) out(`        case .${s.name}: return ${num(s[field])}`);
  out('        }');
  out('    }');
}
out('}');

// ── Type ────────────────────────────────────────────────────────────────────

const weights = { 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold', 800: 'heavy', 900: 'black' };
const order = ['display', 'headline-1', 'headline-2', 'headline-3', 'headline-4', 'subtitle-1', 'label', 'body-1', 'body-2', 'button', 'caption'];
const rank = (s) => (order.includes(s) ? order.indexOf(s) : order.length);
const styles = [...new Set([...group(rootDecls, 'type-').keys()]
  .map((k) => k.match(/^(.+)-(size|weight|line|tracking)$/)?.[1])
  .filter(Boolean))]
  .sort((a, b) => rank(a) - rank(b));

function metrics(style, decls) {
  const get = (prop) => decls.get(`type-${style}-${prop}`) ?? rootDecls.get(`type-${style}-${prop}`);
  const size = px(get('size'), `type-${style}-size`);
  const weight = weights[get('weight')];
  if (!weight) throw new Error(`--type-${style}-weight: unsupported ${get('weight')}`);
  const lineValue = get('line');
  // 100% is the font's own line height, so it needs no adjustment.
  const line = lineValue.endsWith('%')
    ? (Number.parseFloat(lineValue) === 100 ? null : (size * Number.parseFloat(lineValue)) / 100)
    : px(lineValue, `type-${style}-line`);
  const tracking = px(get('tracking'), `type-${style}-tracking`);
  return `SPTypeMetrics(size: ${num(size)}, weight: .${weight}, lineHeight: ${line === null ? 'nil' : num(line)}, tracking: ${num(tracking)})`;
}

const family = rootDecls.get('type-font-family-base')?.match(/'([^']+)'/)?.[1];
if (!family) throw new Error('--type-font-family-base not found');

out();
out('/// Text styles (`--type-*`). Apply with `.spType(_:)`.');
out('///');
out('/// Responsive styles use their `@media (min-width: 768px)` values at regular width (iPad).');
out('public enum SPType: String, CaseIterable, Sendable {');
for (const style of styles) out(`    case ${camel(style)} = "--type-${style}"`);
out();
out('    /// `--type-font-family-base`');
out(`    static let baseFamily = "${family}"`);
out();
out('    func metrics(regularWidth: Bool) -> SPTypeMetrics {');
out('        switch (self, regularWidth) {');
for (const style of styles) {
  const compact = metrics(style, rootDecls);
  const regular = metrics(style, regularDecls);
  if (compact === regular) {
    out(`        case (.${camel(style)}, _): return ${compact}`);
  } else {
    out(`        case (.${camel(style)}, false): return ${compact}`);
    out(`        case (.${camel(style)}, true): return ${regular}`);
  }
}
out('        }');
out('    }');
out('}');
out();

writeFileSync(outPath, lines.join('\n'));
console.log(`Tokens: ${primitives.size} primitives, ${colors.length} colors, ${shadows.length} shadows, ${styles.length} type styles -> ${outPath.replace(root + '/', '')}`);
